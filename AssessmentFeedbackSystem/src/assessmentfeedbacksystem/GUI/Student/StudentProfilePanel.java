    private void setupRow(JPanel row, JLabel label, JComponent field, boolean readonly) {
        row.setBackground(Color.WHITE);
        row.setLayout(new GridBagLayout());
        row.setMaximumSize(new Dimension(Integer.MAX_VALUE, 35));

        label.setFont(new Font("Helvetica Neue", Font.PLAIN, 14));
        label.setForeground(new Color(100, 116, 139));
        label.setPreferredSize(new Dimension(120, 28));

        if (field instanceof JTextField) {
            ((JTextField) field).setFont(new Font("Helvetica Neue", Font.PLAIN, 14));
            ((JTextField) field).setForeground(new Color(30, 41, 59));
            ((JTextField) field).setEditable(!readonly);
            if (readonly) {
                ((JTextField) field).setBackground(new Color(226, 232, 240));
            }
        }
        if (field instanceof JPasswordField) {
            ((JPasswordField) field).setFont(new Font("Helvetica Neue", Font.PLAIN, 14));
            ((JPasswordField) field).setForeground(new Color(30, 41, 59));
        }

        GridBagConstraints gbc = new GridBagConstraints();
        gbc.gridx = 0; gbc.gridy = 0; gbc.weightx = 0; gbc.fill = GridBagConstraints.NONE;
        gbc.insets = new Insets(0, 0, 0, 12);
        gbc.anchor = GridBagConstraints.WEST;
        row.add(label, gbc);

        gbc = new GridBagConstraints();
        gbc.gridx = 1; gbc.gridy = 0; gbc.weightx = 1; gbc.fill = GridBagConstraints.HORIZONTAL;
        gbc.anchor = GridBagConstraints.WEST;
        row.add(field, gbc);
    }

