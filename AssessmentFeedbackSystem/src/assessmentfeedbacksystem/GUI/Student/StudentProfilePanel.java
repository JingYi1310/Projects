    private void loadProfileData() {
        String[] userData = dataService.loadStudentData(currentUsername);

        if (userData != null && userData.length >= 4) {
            lblName.setText(userData[1]);
            lblStudentId.setText("Student ID: " + currentUsername);
            lblAvatar.setText(buildInitials(userData[1]));
            txtFullName.setText(userData[1]);
            txtEmail.setText(userData[2]);
            if (userData.length >= 7) {
                txtContact.setText(userData[6]);
            }
            if (userData.length >= 8) {
                txtRole.setText(userData[7]);
            }
            txtStudentId.setText(currentUsername);
        }

        int enrolledCount = dataService.getEnrolledClassIds(currentUsername).size();
        double gpa = dataService.calculateGpa(currentUsername);
        int completedAssessments = dataService.getResults(currentUsername).size();

        lblEnrolledValue.setText(String.valueOf(enrolledCount));
        lblGpaValue.setText(String.format("%.2f", gpa));
        lblCompletedValue.setText(String.valueOf(completedAssessments));
    }

    private String buildInitials(String name) {
        if (name == null || name.isBlank()) return "S";
        String[] parts = name.trim().split("\\s+");
        String first = parts[0].substring(0, 1).toUpperCase();
        String second = parts.length > 1 ? parts[parts.length - 1].substring(0, 1).toUpperCase() : "";
        return first + second;
    }

    private void openChangePasswordDialog() {
        JPasswordField oldPass = new JPasswordField(14);
        JPasswordField newPass = new JPasswordField(14);
        JPasswordField confirmPass = new JPasswordField(14);

        JPanel panel = new JPanel(new GridLayout(0, 1, 6, 6));
        panel.add(new JLabel("Current password"));
        panel.add(oldPass);
        panel.add(new JLabel("New password"));
        panel.add(newPass);
        panel.add(new JLabel("Confirm new password"));
        panel.add(confirmPass);

        int result = JOptionPane.showConfirmDialog(
                this, panel, "Change Password",
                JOptionPane.OK_CANCEL_OPTION, JOptionPane.PLAIN_MESSAGE
        );

        if (result != JOptionPane.OK_OPTION) return;

        String oldVal = new String(oldPass.getPassword());
        String newVal = new String(newPass.getPassword());
        String confirmVal = new String(confirmPass.getPassword());

        if (oldVal.isEmpty() || newVal.isEmpty() || confirmVal.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill in all password fields.",
                    "Missing Information", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!User.verifyPassword(currentUsername, oldVal)) {
            JOptionPane.showMessageDialog(this, "Current password is incorrect.",
                    "Invalid Password", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (!newVal.equals(confirmVal)) {
            JOptionPane.showMessageDialog(this, "New passwords do not match.",
                    "Mismatch", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (oldVal.equals(newVal)) {
            JOptionPane.showMessageDialog(this, "New password must be different from current password.",
                    "Invalid Password", JOptionPane.ERROR_MESSAGE);
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(
                this, "Are you sure you want to change your password?",
                "Confirm Change", JOptionPane.YES_NO_OPTION
        );
        if (confirm != JOptionPane.YES_OPTION) return;

        boolean updated = User.updatePassword(currentUsername, newVal);
        if (updated) {
            JOptionPane.showMessageDialog(this, "Password updated successfully.",
                    "Success", JOptionPane.INFORMATION_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this, "Failed to update password.",
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
