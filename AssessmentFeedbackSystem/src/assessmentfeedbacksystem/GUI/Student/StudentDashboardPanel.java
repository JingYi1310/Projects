    private static class ScheduleListRenderer extends DefaultListCellRenderer {
        @Override
        public Component getListCellRendererComponent(
                JList<?> list, Object value, int index, boolean isSelected, boolean cellHasFocus) {
            if (value instanceof String) {
                JLabel label = (JLabel) super.getListCellRendererComponent(
                        list, value, index, isSelected, cellHasFocus
                );
                label.setBorder(javax.swing.BorderFactory.createEmptyBorder(12, 8, 12, 8));
                label.setForeground(new Color(100, 116, 139));
                label.setBackground(Color.WHITE);
                return label;
            }

            ClassModel c = (ClassModel) value;
            JPanel row = new JPanel(new BorderLayout(10, 4));
            row.setBackground(Color.WHITE);
            row.setBorder(javax.swing.BorderFactory.createCompoundBorder(
                    javax.swing.BorderFactory.createMatteBorder(0, 0, 1, 0, new Color(226, 232, 240)),
                    javax.swing.BorderFactory.createEmptyBorder(10, 8, 10, 8)
            ));

            JLabel code = new JLabel(c.getClassName());
            code.setFont(new Font("Helvetica Neue", Font.BOLD, 14));
            code.setForeground(new Color(15, 23, 42));

            JLabel time = new JLabel(c.getStartTime() + " - " + c.getEndTime());
            time.setFont(new Font("Helvetica Neue", Font.PLAIN, 12));
            time.setForeground(new Color(100, 116, 139));

            row.add(code, BorderLayout.NORTH);
            row.add(time, BorderLayout.SOUTH);
            return row;
        }
    }
