    private void onEnrollmentChanged(String studentId) {
        if (currentUsername == null || !currentUsername.equals(studentId)) return;
        javax.swing.SwingUtilities.invokeLater(this::loadDashboardData);
    }
    
    private void loadDashboardData() {
        // Load student data
        String[] userData = dataService.loadStudentData(currentUsername);
        
        // welcome
        if (userData != null && userData.length >= 2) {
            lblWelcome.setText("Welcome back, " + userData[1] + "!");
        } else {
            lblWelcome.setText("Welcome back, Student!");
        }
        
        // today
        LocalDate today = LocalDate.now();

        String formattedDate =
                today.getDayOfMonth() + " " +
                today.getMonth().getDisplayName(TextStyle.FULL, Locale.ENGLISH) + " " +
                today.getYear() + ", " +
                today.getDayOfWeek().getDisplayName(TextStyle.FULL, Locale.ENGLISH);

        lblTodayDate.setText(formattedDate);

        // Get enrolled classes
        List<ClassModel> enrolledClasses = dataService.getEnrolledClasses(currentUsername);
        int enrolledCount = enrolledClasses.size();
        
        // Calculate GPA
        double cgpa = dataService.calculateCgpa(currentUsername);
        
        // Get today's classes
        String todayDayName = today.getDayOfWeek().toString();
        List<ClassModel> todaysClasses = enrolledClasses.stream()
            .filter(c -> c.getDay().toString().equalsIgnoreCase(todayDayName))
            .toList();
        int todaysClassCount = todaysClasses.size();

        // Update widget values
        lblEnrolledValue.setText(String.valueOf(enrolledCount));
        lblGPAValue.setText(String.format("%.2f", cgpa));

        // Schedule list under chart placeholder
        todayScheduleModel.clear();
        if (todaysClasses.isEmpty()) {
            todayScheduleModel.addElement("No classes today!");
        } else {
            for (ClassModel c : todaysClasses) {
                todayScheduleModel.addElement(c);
            }
        }
    }
    
