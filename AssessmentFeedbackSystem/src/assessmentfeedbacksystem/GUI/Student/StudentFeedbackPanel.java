    private void loadFeedbackData() {
        loadTargets();
        List<Feedback> feedbacks = dataService.getFeedbacks(currentUsername);
        feedbackRows.clear();
        feedbackTableModel.setRowCount(0);

        feedbacks.sort((a, b) -> {
            if (a.getSubmittedAt() == null && b.getSubmittedAt() == null) return 0;
            if (a.getSubmittedAt() == null) return 1;
            if (b.getSubmittedAt() == null) return -1;
            return b.getSubmittedAt().compareTo(a.getSubmittedAt());
        });

        for (Feedback feedback : feedbacks) {
            String lecturerName = feedback.getLecturer() != null
                    ? Lecturer.getLecturerNameById(feedback.getLecturer().getUser_id())
                    : "Unknown Lecturer";
            String moduleName = feedback.getClassModel() != null && feedback.getClassModel().getModule() != null
                    ? feedback.getClassModel().getModule().getModuleName()
                    : "Module";
            String label = moduleName + " (" + lecturerName + ")";
            String date = feedback.getSubmittedAt() != null
                    ? feedback.getSubmittedAt().toString()
                    : "";
            feedbackRows.add(feedback);
            feedbackTableModel.addRow(new Object[]{label, date});
        }
    }
    
    private void loadTargets() {
        targetModel.removeAllElements();
        if (currentUsername == null || currentUsername.isEmpty()) {
            return;
        }
        List<String> classIds = dataService.getEnrolledClassIds(currentUsername);
        for (String classId : classIds) {
            ClassModel c = ClassModel.getClassById(classId);
            if (c == null || c.getModule() == null) continue;
            String lecturerId = c.getModule().getLecturer() != null
                    ? c.getModule().getLecturer().getUser_id()
                    : null;
            String lecturerName = lecturerId != null
                    ? Lecturer.getLecturerNameById(lecturerId)
                    : "Unknown Lecturer";
            String moduleLabel = c.getModule().getModuleCode() + " - " + c.getModule().getModuleName();
            String label = moduleLabel + " (" + lecturerName + ")";
            targetModel.addElement(new FeedbackTarget(classId, lecturerId, label));
        }
    }

    private void submitFeedback() {
        lblSubmitStatus.setText(" ");
        FeedbackTarget target = (FeedbackTarget) cmbTarget.getSelectedItem();
        if (target == null) {
            setSubmitStatus("Please select a module.", false);
            return;
        }
        if (dataService.hasFeedbackForClass(currentUsername, target.classId)) {
            setSubmitStatus("You can only submit one feedback per module/lecturer.", false);
            return;
        }
        String comment = txtComment.getText().trim();
        if (comment.isEmpty()) {
            setSubmitStatus("Please enter a comment.", false);
            return;
        }
        int rating = sldRating.getValue();
        String category = (String) cmbCategory.getSelectedItem();

        boolean ok = dataService.submitFeedback(currentUsername, target.lecturerId, target.classId,
                                             rating, category, comment);
        if (ok) {
            setSubmitStatus("Feedback submitted successfully.", true);
            txtComment.setText("");
            loadFeedbackData();
        } else {
            setSubmitStatus("Failed to submit feedback.", false);
        }
    }

    private void showSelectedFeedbackDetail() {
        int row = tblFeedback.getSelectedRow();
        if (row < 0 || row >= feedbackRows.size()) {
            return;
        }
        Feedback selected = feedbackRows.get(row);
        String lecturerName = selected.getLecturer() != null
                ? Lecturer.getLecturerNameById(selected.getLecturer().getUser_id())
                : "Unknown Lecturer";
        String moduleName = selected.getClassModel() != null && selected.getClassModel().getModule() != null
                ? selected.getClassModel().getModule().getModuleName()
                : "Module";
        String date = selected.getSubmittedAt() != null
                ? selected.getSubmittedAt().toString()
                : "";
        String detail = ""
                + "Module / Lecturer: " + moduleName + " (" + lecturerName + ")\n"
                + "Date: " + date + "\n"
                + "Category: " + selected.getCategory() + "\n"
                + "Rating: " + selected.getRating() + "\n\n"
                + "Comment:\n" + (selected.getComment() != null ? selected.getComment() : "");
        JOptionPane.showMessageDialog(this, detail, "Feedback Details", JOptionPane.INFORMATION_MESSAGE);
    }

    private void setSubmitStatus(String message, boolean success) {
        lblSubmitStatus.setText(message);
        if (success) {
            lblSubmitStatus.setForeground(new Color(22, 163, 74));
        } else {
            lblSubmitStatus.setForeground(new Color(220, 38, 38));
        }
    }

    private static class FeedbackTarget {
        private final String classId;
        private final String lecturerId;
        private final String label;

        FeedbackTarget(String classId, String lecturerId, String label) {
            this.classId = classId;
            this.lecturerId = lecturerId;
            this.label = label;
        }

        @Override
        public String toString() {
            return label;
        }
    }
