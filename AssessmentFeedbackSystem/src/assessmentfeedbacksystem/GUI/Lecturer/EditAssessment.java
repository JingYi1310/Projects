    public EditAssessment(MainFrame mainFrame, String selected_class_id, Lecturer logged_in_user, Assessment assessment) {
        this.assessment = assessment;
        this.mainFrame = mainFrame;
        this.selected_class_id = selected_class_id;
        this.logged_in_user = logged_in_user;
        module_id = ClassModel.getModuleByClassId(selected_class_id).getModuleId();
        
        initComponents();
        
        // Inactive class - set to view only
        String module_status = ClassModel.getModuleByClassId(selected_class_id).getStatus();
        if ("Inactive".equalsIgnoreCase(module_status)){
            AssessmentCode.setEnabled(false);
            AssessmentName.setEnabled(false);
            Percentage.setEnabled(false);
            Type.setEnabled(false);
            TotalMarks.setEnabled(false);
            messageForRemainingPercentage.setVisible(false);
            PublishBtn.setVisible(false);
            SaveAsDraftBtn.setVisible(false);
            DeleteBtn.setVisible(false);
        }
        
        int selectedIndex = 0;
        int loop = 1;
        Type.addItem("Please select a assessment type");
        for (AssessmentType type : AssessmentType.values()) {
            Type.addItem(type.toString());
            if (assessment.getAssessmentType().equals(type)){
                selectedIndex = loop;
            }
            loop ++;
        }
        
        AssessmentCode.setText(assessment.getAssessmentId());
        AssessmentName.setText(assessment.getAssessmentName());
        try {
            Type.setSelectedIndex(selectedIndex);
        }catch (ArrayIndexOutOfBoundsException e){
            Type.setSelectedIndex(0);
        }
        TotalMarks.setValue(assessment.getTotalMarks());
        if (Assessment.remainingPercentage(module_id) == 0 && assessment.getWeightPercentage() == 0){
            Percentage.setEnabled(false);
            Percentage.setFocusable(false);
        }else{
            Percentage.setModel(new javax.swing.SpinnerNumberModel(assessment.getWeightPercentage(), 0, Assessment.remainingPercentage(module_id)+ assessment.getWeightPercentage(), 1));
        }
        messageForRemainingPercentage.setText("Remaining Percentage: " + (Assessment.remainingPercentage(module_id)+ assessment.getWeightPercentage()));
    }
    
    public String formatStringData(AssessmentStatus status){
        String id = AssessmentCode.getText();
        String name = AssessmentName.getText();
        String type = Type.getItemAt(Type.getSelectedIndex());
        String totalMarks = TotalMarks.getValue().toString();
        String percentage = Percentage.getValue().toString();
        LocalDate today = LocalDate.now();
        
        String data = String.join(";", id, name, type, module_id, 
                totalMarks, percentage, status.toString(), logged_in_user.getUser_id(), today.toString());
        
        return data;
    }
   
