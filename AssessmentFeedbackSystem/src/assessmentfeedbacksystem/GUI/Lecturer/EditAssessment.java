    private void PublishBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_PublishBtnActionPerformed
        int weightage = (int) Percentage.getValue();
        int total = 100 - Assessment.remainingPercentage(module_id);
        
        if (AssessmentCode.getText().trim().isEmpty() || AssessmentName.getText().trim().isEmpty() || Type.getSelectedIndex() == 0 || (int) TotalMarks.getValue() == 0 || (int) Percentage.getValue() < 0){
            JOptionPane.showMessageDialog(null,
                "Please fill in all fields correctly before publishing.\n" +
                "- Make sure Assessment Code and Name are not empty.\n" +
                "- Select an Assessment Type.\n" +
                "- Total Marks must be greater than 0.\n" +
                "- Percentage must be greater or equals to 0.",
                "Incomplete Form",
                JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        // CASE 1: Zero-weightage assessment
        if (weightage == 0) {
            int confirm = JOptionPane.showConfirmDialog(
                null, 
                """
                    This assessment has 0% weightage and will NOT affect the final result.

                    Do you want to publish it now?""",
                "Publish Practice Assessment",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.INFORMATION_MESSAGE
            );

            if (confirm == JOptionPane.YES_OPTION) {
                Assessment.saveOrUpdateAssessment(formatStringData(AssessmentStatus.PUBLISHED));
                JOptionPane.showMessageDialog(
                    null,
                    AssessmentName.getText() + " has been published.",
                    "Published",
                    JOptionPane.INFORMATION_MESSAGE
                );
                mainFrame.showClassDetail(selected_class_id, AssessmentStatus.PUBLISHED);
            }
            return;
        }

        // CASE 2: Weighted assessments – total must be exactly 100
        if (total == 100) {
            List<Assessment> list = Assessment.getWeightedAssessments(module_id);

            StringBuilder message = new StringBuilder();
            message.append("The following assessments will be published:\n\n");

            for (Assessment a : list) {
                message.append("• ")
                        .append(a.getAssessmentName())
                        .append("(")
                        .append(a.getAssessmentType())
                        .append(")")
                        .append(" – ")
                        .append(a.getWeightPercentage())
                        .append("%\n");
            }

            message.append("\nTotal weightage: 100%\n\n")
                   .append("Published assessments cannot be edited or deleted.\n")
                   .append("Students will be able to view their results.\n\n")
                   .append("Do you want to proceed?");

            int confirm = JOptionPane.showConfirmDialog(
                null,
                message.toString(),
                "Confirm Publish Final Assessments",
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE
            );

            if (confirm == JOptionPane.YES_OPTION) {
                Assessment.saveOrUpdateAssessment(formatStringData(AssessmentStatus.DRAFT));
                String error = Assessment.publishAllFinalAssessments(module_id);
                if (error == null){
                    JOptionPane.showMessageDialog(
                        null,
                        "Final assessments published successfully.",
                        "Publish Successful",
                        JOptionPane.INFORMATION_MESSAGE
                    );
                    mainFrame.showClassDetail(selected_class_id, AssessmentStatus.PUBLISHED);
                }else{
                    JOptionPane.showMessageDialog(
                        null,
                        error,
                        "Publish Failed",
                        JOptionPane.ERROR_MESSAGE
                    );
                }
            }
            return;
        }

        // CASE 3: Invalid total
        JOptionPane.showMessageDialog(
            null,
            """
            You must allocate exactly 100% before publishing.
            
            Current total: """ + total + "%",
            "Cannot Publish",
            JOptionPane.WARNING_MESSAGE
        );
    }//GEN-LAST:event_PublishBtnActionPerformed

