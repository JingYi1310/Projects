    private void EditOrSaveBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EditOrSaveBtnActionPerformed
        if ("Edit".equals(state)){
            String email = EmailText.getText().trim();
            String contact = ContactNoText.getText().trim();
            String password = new String(PasswordText.getPassword()).trim();

            if (email.isEmpty() || contact.isEmpty()) {
                JOptionPane.showMessageDialog(
                    null,
                    "Please fill in all required fields.",
                    "Validation Error",
                    JOptionPane.WARNING_MESSAGE
                );
                return;
            }

            boolean success = User.updateProfile(
                logged_in_user.getUser_id(),
                email,
                contact,
                password.isEmpty() ? null : password
            );

            if (!success) {
                JOptionPane.showMessageDialog(
                    null,
                    "Failed to update profile.",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
                );
                return;
            }
            JOptionPane.showMessageDialog(
                    null,
                    "Profile successfully updated.",
                    "Success",
                    JOptionPane.INFORMATION_MESSAGE
                );
            viewState();
            state = "View";
        }else{
            editState();
            state = "Edit";
        }
    }//GEN-LAST:event_EditOrSaveBtnActionPerformed


