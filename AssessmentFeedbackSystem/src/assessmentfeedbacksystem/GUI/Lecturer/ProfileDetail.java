    private void initValue(Lecturer logged_in_user){
        UserIdText.setText(logged_in_user.getUser_id());
        UserNameText.setText(logged_in_user.getName());
        
        if ("F".equals(logged_in_user.getGender())){
            GenderText.setText("Female");
        }else if ("M".equals(logged_in_user.getGender())){
            GenderText.setText("Male");
        }else{
            GenderText.setText("-");
        }
        
        DOBText.setText(logged_in_user.getDob().toString());
        EmailText.setText(logged_in_user.getEmail());
        ContactNoText.setText(logged_in_user.getContact_no());
        RoleText.setText(logged_in_user.getRole());
        DepartmentText.setText(logged_in_user.getDepartment());
        AcademicLeaderNameText.setText(AcademicLeader.getUserNameById(logged_in_user.getLeaderId()));
        PasswordText.setText(logged_in_user.getPassword());
    }

