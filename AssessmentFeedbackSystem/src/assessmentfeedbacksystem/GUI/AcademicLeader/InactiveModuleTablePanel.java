    private void loadInactiveModules() {
        DefaultTableModel model = (DefaultTableModel) tblInactiveModules.getModel();
        model.setRowCount(0);
        
        if (logged_in_al == null) {
            return;
        }

        for (Module m : Module.getInactiveModules()) {
            
            if (!m.getCreatedBy().equals(logged_in_al.getUser_id())) {
                continue;
            }           
            
            model.addRow(new Object[]{
                m.getModuleId(),
                m.getModuleCode(),
                m.getModuleName(),
                Lecturer.getLecturerNameById(m.getLecturer().getUser_id()),
                m.getStatus(),
            });
        }
    }
    
    public void reloadInactiveTable() {
        DefaultTableModel model = (DefaultTableModel) tblInactiveModules.getModel();
        model.setRowCount(0);
        
        if (logged_in_al == null) {
            return;
        }

        for (Module m : Module.getInactiveModules()) {
            
            if (!m.getCreatedBy().equals(logged_in_al.getUser_id())) {
                continue;
            }
            
            model.addRow(new Object[]{
                m.getModuleId(),
                m.getModuleCode(),
                m.getModuleName(),
                Lecturer.getLecturerNameById(m.getLecturer().getUser_id()),
                m.getStatus(),
            });
        }
    }

