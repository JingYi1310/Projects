    private void tblInactiveModulesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblInactiveModulesMouseClicked
        // TODO add your handling code here:
        if (parent == null) {
            return;
        }
        
        int row = tblInactiveModules.getSelectedRow();
        if (row < 0) {
            return;
        }

        String moduleId = tblInactiveModules.getValueAt(row, 0).toString();

        for (Module m : Module.getInactiveModules()) { 
            if (m.getModuleId().equals(moduleId)) {
                parent.showDetail(m);
                break;
            }
        }
    }//GEN-LAST:event_tblInactiveModulesMouseClicked


