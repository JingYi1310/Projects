    private void btnExportActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportActionPerformed
        // TODO add your handling code here:
        try {
            javax.swing.JFileChooser chooser = new javax.swing.JFileChooser();
            chooser.setDialogTitle("Save Report as PDF");

            if (chooser.showSaveDialog(null) != javax.swing.JFileChooser.APPROVE_OPTION) {
                return;
            }

            java.io.File file = chooser.getSelectedFile();
            if (!file.getName().toLowerCase().endsWith(".pdf")) {
                file = new java.io.File(file.getAbsolutePath() + ".pdf");
            }

            boolean exportBtnVisible = btnExport.isVisible();
            btnExport.setVisible(false);
            java.awt.image.BufferedImage headerImg = capturePanel(headerContentPanel);
            btnExport.setVisible(exportBtnVisible);

            java.awt.image.BufferedImage chartImg  = capturePanel(chartContainerPanel);
            java.awt.image.BufferedImage tableImg  = capturePanel(tableContainerPanel);

            com.itextpdf.text.Image header = com.itextpdf.text.Image.getInstance(headerImg, null);
            com.itextpdf.text.Image chart  = com.itextpdf.text.Image.getInstance(chartImg, null);
            com.itextpdf.text.Image table  = com.itextpdf.text.Image.getInstance(tableImg, null);

            float pageWidth =
            com.itextpdf.text.PageSize.A4.getWidth() - 80;

            header.scaleToFit(pageWidth, 200);
            chart.scaleToFit(pageWidth, 400);
            table.scaleToFit(pageWidth, 500);   

            com.itextpdf.text.Document document =
            new com.itextpdf.text.Document(
                com.itextpdf.text.PageSize.A4,
                40, 40, 50, 50
            );

            com.itextpdf.text.pdf.PdfWriter writer =
                com.itextpdf.text.pdf.PdfWriter.getInstance(
                    document,
                    new java.io.FileOutputStream(file)
                );

            writer.setPageEvent(new assessmentfeedbacksystem.PdfHeaderFooter());

            document.open();

            document.add(header);
            document.add(com.itextpdf.text.Chunk.NEWLINE);
            document.add(chart);
            document.add(table);

            document.close();
            
            int choice = javax.swing.JOptionPane.showConfirmDialog(
                null,
                "Report exported successfully.\n\nDo you want to open the PDF now?",
                "Export Complete",
                javax.swing.JOptionPane.YES_NO_OPTION,
                javax.swing.JOptionPane.QUESTION_MESSAGE
            );

            if (choice == javax.swing.JOptionPane.YES_OPTION) {
                if (java.awt.Desktop.isDesktopSupported()) {
                    java.awt.Desktop.getDesktop().open(file);
                }
            }

//            javax.swing.JOptionPane.showMessageDialog(
//                this,
//                "Report exported successfully!",
//                "Export Complete",
//                javax.swing.JOptionPane.INFORMATION_MESSAGE
//            );

        } catch (Exception ex) {
            ex.printStackTrace();
            javax.swing.JOptionPane.showMessageDialog(
                null,
                "Failed to export report.",
                "Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btnExportActionPerformed

    private java.awt.image.BufferedImage capturePanel(javax.swing.JComponent panel) {
        java.awt.image.BufferedImage image =
            new java.awt.image.BufferedImage(
                panel.getWidth(),
                panel.getHeight(),
                java.awt.image.BufferedImage.TYPE_INT_RGB
            );

        java.awt.Graphics2D g2 = image.createGraphics();
        g2.setColor(java.awt.Color.WHITE);
        g2.fillRect(0, 0, image.getWidth(), image.getHeight());
        panel.paint(g2);
        g2.dispose();

        return image;
    }

