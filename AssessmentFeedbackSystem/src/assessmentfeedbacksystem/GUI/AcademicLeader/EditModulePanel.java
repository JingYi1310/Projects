    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        if (currentModule == null) return;
        
        String code = txtModuleCode.getText().trim();
        String name = txtModuleName.getText().trim();
        double credit = ((Number) spnCreditHour.getValue()).doubleValue();

        if (code.isEmpty() || name.isEmpty()) {
            JOptionPane.showMessageDialog(
                null,
                "Please fill in all required fields.",
                "Validation Error",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        currentModule.setModuleCode(code);
        currentModule.setModuleName(name);
        currentModule.setCreditHour(credit);

        String lecturerItem = cmbLecturer.getSelectedItem().toString();
//        currentModule.setLecturerId(lecturerItem.split(" - ")[0]);
        currentModule.setLecturer(Lecturer.getLecturerById(lecturerItem.split(" - ")[0]));
        
        boolean success = Module.updateModule(currentModule);

        if (success) {
            JOptionPane.showMessageDialog(null, "Module updated successfully.","Success",JOptionPane.INFORMATION_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(null, "Failed to update module.","Error",JOptionPane.ERROR_MESSAGE);
        }

        parent.showDetail(currentModule);
    }//GEN-LAST:event_btnSaveActionPerformed

