    private void loadLecturers() {
        cmbLecturer.removeAllItems();

        for (String line : FileManager.readFile("User.txt")) {
            String[] data = line.split(";");
            if (data.length < 12) continue;

            if (data[7].equals("Lecturer") &&
                data[11].equals(logged_in_al.getUser_id())) {
                cmbLecturer.addItem(data[0] + " - " + data[1]);
            }
        }
    }
    
    public void setModule(Module m) {
        this.currentModule = m;

        txtModuleCode.setText(m.getModuleCode());
        txtModuleName.setText(m.getModuleName());
        spnCreditHour.setValue(m.getCreditHour());

        for (int i = 0; i < cmbLecturer.getItemCount(); i++) {
            if (cmbLecturer.getItemAt(i).startsWith(m.getLecturer().getUser_id())) {
                cmbLecturer.setSelectedIndex(i);
                break;
            }
        }
        
        ClassModel c = ClassModel.getClassByModuleId(m.getModuleId());
        
        if (c != null) {
            lblStudentCountValue.setText(String.valueOf(ClassModel.getNoOfStudentInClass(c.getClassId())));     
        } else {
            lblStudentCountValue.setText("0 (Waiting for class to be created)");
        }
        
        lblDateValue.setText(m.getDateCreated().toString());
    }

