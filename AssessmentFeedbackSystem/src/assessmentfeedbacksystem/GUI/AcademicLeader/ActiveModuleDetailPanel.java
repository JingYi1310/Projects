    private void btnDeactivateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeactivateActionPerformed
        // TODO add your handling code here:
        if (currentModule == null) {
            return;
        }

        String actionText = deleteMode ? "delete" : "deactivate";
        String actionTitle = deleteMode ? "Delete" : "Deactivate";

        int confirm = JOptionPane.showConfirmDialog(
            null,
            "Are you sure you want to " + actionText + " this module?\nThis action cannot be undone.",
            "Confirm " + actionTitle,
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE
        );

        if (confirm != JOptionPane.YES_OPTION) {
            return; 
        }

        boolean success;

        if (deleteMode) {
            success = Module.deleteModule(
                currentModule.getModuleId(),
                false
            );
        } else {
            success = Module.deactivateModule(
                currentModule.getModuleId(),
                true
            );
        }

        if (success) {
            JOptionPane.showMessageDialog(
                null,
                "Module successfully " + (deleteMode ? "deleted." : "deactivated."),
                "Success",
                JOptionPane.INFORMATION_MESSAGE
            );
            
            if (deleteMode) {
                parent.showTable();
            } else {
                ModuleManagementPanel parentPanel = (ModuleManagementPanel) SwingUtilities.getAncestorOfClass(ModuleManagementPanel.class, this);
                if (parentPanel != null) {
                    parentPanel.getTabMain().setSelectedComponent(parentPanel.getPnlInactive());
                    parentPanel.getInactiveModuleContainerPanel().showTable(); 
                }
            }
        } else {
            JOptionPane.showMessageDialog(
                null,
                "Operation failed. Please try again.",
                "Error",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btnDeactivateActionPerformed

