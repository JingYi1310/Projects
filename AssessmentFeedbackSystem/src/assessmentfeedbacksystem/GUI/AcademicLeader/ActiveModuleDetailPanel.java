    public void setModule(Module m) {
        this.currentModule = m;
        
        lblModuleCodeValue.setText(m.getModuleCode());
        lblModuleNameValue.setText(m.getModuleName());
        lblCreditHourValue.setText(String.valueOf(m.getCreditHour()));
        lblLecturerValue.setText(Lecturer.getLecturerNameById(m.getLecturer().getUser_id()));
        
        ClassModel c = ClassModel.getClassByModuleId(m.getModuleId());
        
        if (c != null) {
            lblStudentCountValue.setText(String.valueOf(c.getNoOfStudentInClass(c.getClassId())));
            
            // button show "Deactivate" as text
            deleteMode = false;
            btnDeactivate.setText("Deactivate");
            btnDeactivate.setBackground(new java.awt.Color(255, 205, 210));
            btnDeactivate.setForeground(new java.awt.Color(183, 28, 28));
        
        } else {
            lblStudentCountValue.setText("0 (Waiting for class to be created)");
            
            // button show "Delete" as text
            deleteMode = true;
            btnDeactivate.setText("Delete");
            btnDeactivate.setBackground(new java.awt.Color(255, 205, 210));
            btnDeactivate.setForeground(new java.awt.Color(183, 28, 28));
        }
        
        lblDateValue.setText(m.getDateCreated().toString());
    }

