    public CreateClassFrame(AdminStaff admin) {
  
        initComponents();
        
        this.logged_in_admin = admin;
        
        // Display Module ID
        List<Module> allModules = Module.getAllModules();
        List<ClassModel> allClasses = ClassModel.readAllClasses();
        Set<String> usedModuleIds = allClasses.stream() // loop one by one
                                              .map(c -> c.getModule().getModuleId()) // return module id
                                              .collect(Collectors.toSet()); // put into set
        moduleIdComboBox.removeAllItems();
        for(Module module: allModules){
            if(!usedModuleIds.contains(module.getModuleId())){
                moduleIdComboBox.addItem(module.getModuleId());
            }
        }
        
        // Initial display
        updateModuleName(allModules);

        // Switch module name text
        moduleIdComboBox.addActionListener(e -> updateModuleName(allModules));
        
        // If no module available disabled all input
        if (moduleIdComboBox.getItemCount() == 0) {
            moduleIdComboBox.setEnabled(false);
            className_field.setEnabled(false);
            dayComboBox.setEnabled(false);
            durationComboBox.setEnabled(false);
            startTimeSpinner.setEnabled(false);
            endTimeSpinner.setEnabled(false);
            createButton.setEnabled(false);
            JOptionPane.showMessageDialog(this, "All modules already have classes. Cannot create new class.");
        }
        
        // Identify Class ID
        classId_field.setText(generateClassId());
        classId_field.setEditable(false);
        
        // Set up duration
        durationComboBox.removeAllItems();
        for (int mins : duration_in_minutes) {
            String text = (mins >= 60) ? (mins / 60) + "h " + (mins % 60) + "m" : mins + " mins";
            durationComboBox.addItem(text);
        }
        
        setUpStartTimeSpinner();
        setUpEndTimeSpinner();

        
        
    }

