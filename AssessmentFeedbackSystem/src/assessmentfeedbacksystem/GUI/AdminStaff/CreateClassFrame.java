    public boolean checkValidation() {

        if (moduleIdComboBox.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Please select a module.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            moduleIdComboBox.requestFocus();
            return false;
        }

        String className = className_field.getText().trim();
        if (className.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Class name cannot be empty.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            className_field.requestFocus();
            return false;
        }
        if (className.length() < 2 || className.length() > 50) {
            JOptionPane.showMessageDialog(this, "Class name must be between 2 and 50 characters.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            className_field.requestFocus();
            return false;
        }

        if (dayComboBox.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Please select a day.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            dayComboBox.requestFocus();
            return false;
        }

        if (durationComboBox.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Please select a duration.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            durationComboBox.requestFocus();
            return false;
        }

        Date startTime = (Date) startTimeSpinner.getValue();
        if (startTime == null) {
            JOptionPane.showMessageDialog(this, "Please select a valid start time.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            startTimeSpinner.requestFocus();
            return false;
        }

        Date endTime = (Date) endTimeSpinner.getValue();
        if (endTime == null) {
            JOptionPane.showMessageDialog(this, "End time cannot be empty.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            endTimeSpinner.requestFocus();
            return false;
        }

        return true;
    }

    
    public String generateClassId(){
        
        String prefix = "C";
        int max_number = 0;
        
        List<ClassModel> allClasses = ClassModel.readAllClasses();
        for(ClassModel c: allClasses){
            String class_id = c.getClassId();
            System.out.println("Class ID: " + class_id);
            
            if(class_id.startsWith(prefix)){
                
                // cut off part
                String numeric_part = class_id.substring(prefix.length());
                try{
                    int num = Integer.parseInt(numeric_part);
                    if(num > max_number){
                        max_number = num;
                    }
                }catch(NumberFormatException e){
                    System.out.println("Skipping invalid class ID: " + class_id);
                }
                
            }
        }
        
        int new_number = max_number + 1;
        return prefix + String.format("%03d", new_number);
    }
    
    public void setUpStartTimeSpinner(){
        
        // Set start time picker
        String minStr = "08:00";
        String maxStr = "18:00";

        SimpleDateFormat sdf = new SimpleDateFormat("HH:mm");

        try {
            Date minTime = sdf.parse(minStr);
            Date maxTime = sdf.parse(maxStr);
            Date initial = minTime;

            startTimeSpinner.setModel(new SpinnerDateModel(initial, minTime, maxTime, Calendar.MINUTE){
                @Override
                public Object getNextValue() {
                    return adjust((Date) super.getNextValue(), true);
                }

                @Override
                public Object getPreviousValue() {
                    return adjust((Date) super.getPreviousValue(), false);
                }

                private Date adjust(Date date, boolean next) {
                    Calendar cal = Calendar.getInstance();
                    cal.setTime(date);
                    int minutes = cal.get(Calendar.MINUTE);

                    if (next) {
                        minutes = ((minutes + 14) / 15) * 15; // round up
                        if (minutes >= 60) {
                            cal.add(Calendar.HOUR_OF_DAY, 1);
                            minutes = 0;
                        }
                    } else {
                        minutes = (minutes / 15) * 15; // round down
                    }

                    cal.set(Calendar.MINUTE, minutes);
                    cal.set(Calendar.SECOND, 0);
                    cal.set(Calendar.MILLISECOND, 0);

                    // Clamp to min/max
                    if (cal.getTime().before((Date) getStart())) cal.setTime((Date) getStart());
                    if (cal.getTime().after((Date) getEnd())) cal.setTime((Date) getEnd());

                    return cal.getTime();
                }
            });

        } catch (ParseException e) {
            e.printStackTrace();
        }
        
        // Editor to display HH:mm
        JSpinner.DateEditor editor = new JSpinner.DateEditor(startTimeSpinner, "HH:mm");
        startTimeSpinner.setEditor(editor);
        
        startTimeSpinner.addChangeListener(e -> {
            Date value = (Date) startTimeSpinner.getValue();
            Calendar cal = Calendar.getInstance();
            cal.setTime(value);

            int minutes = cal.get(Calendar.MINUTE);
            // Round to nearest 15
            minutes = (int) (Math.round(minutes / 15.0) * 15);
            if (minutes >= 60) {
                cal.add(Calendar.HOUR_OF_DAY, 1);
                minutes = 0;
            }
            cal.set(Calendar.MINUTE, minutes);
            cal.set(Calendar.SECOND, 0);
            cal.set(Calendar.MILLISECOND, 0);

            Date adjusted = cal.getTime();

            // Update spinner if changed
            if (!value.equals(adjusted)) {
                startTimeSpinner.setValue(adjusted);
            }
        });
        
    }
    
    public void setUpEndTimeSpinner(){
        
        Calendar cal = Calendar.getInstance();
        cal.setTime((Date) startTimeSpinner.getValue()); // initial start time
        int initialDuration = duration_in_minutes[0]; // first item in duration array
        cal.add(Calendar.MINUTE, initialDuration);
        Date initialEndTime = cal.getTime();

        SpinnerDateModel endTimeModel = new SpinnerDateModel(initialEndTime, null, null, Calendar.MINUTE);
        endTimeSpinner.setModel(endTimeModel);

        // Make endTimeSpinner read-only
        JFormattedTextField endEditor = ((JSpinner.DefaultEditor) endTimeSpinner.getEditor()).getTextField();
        endEditor.setEditable(false);
        endTimeSpinner.setEditor(new JSpinner.DateEditor(endTimeSpinner, "HH:mm"));

        // --- Update endTimeSpinner whenever startTime or duration changes ---
        ChangeListener updateEndTime = e -> {
            Date start = (Date) startTimeSpinner.getValue();

            int selectedIndex = durationComboBox.getSelectedIndex();
            int duration = duration_in_minutes[Math.max(selectedIndex, 0)]; // fallback to first if none selected

            Calendar c = Calendar.getInstance();
            c.setTime(start);
            c.add(Calendar.MINUTE, duration);

            endTimeSpinner.setValue(c.getTime());
        };
        
        // Attach listener to startTimeSpinner
        startTimeSpinner.addChangeListener(updateEndTime);

        // Attach listener to durationComboBox
        durationComboBox.addActionListener(e -> updateEndTime.stateChanged(null));
        
        endTimeSpinner.setEnabled(false);
        
    }
    
