    private void createButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_createButtonActionPerformed
        
        if (!checkValidation()) {
            return;
        }
        
        String module_id = moduleIdComboBox.getSelectedItem().toString();
        String class_id = classId_field.getText();
        String class_name = className_field.getText();
        DayOfWeek day = DayOfWeek.valueOf(dayComboBox.getSelectedItem().toString().toUpperCase());
        String durationText = durationComboBox.getSelectedItem().toString();
        String startTimeText = startTimeSpinner.getValue().toString();
        String endTimeText = endTimeSpinner.getValue().toString();
        
        // Module Object
        Module selected_module = new Module(module_id);
        
        // Convertion (Duration)
        int totalMinutes = 0;

        if (durationText.contains("h")) {
            String[] parts = durationText.split("h");
            int hours = Integer.parseInt(parts[0].trim());
            int minutes = Integer.parseInt(parts[1].replace("m", "").trim());
            totalMinutes = hours * 60 + minutes;
        } else {
            totalMinutes = Integer.parseInt(durationText.replace("mins", "").trim());
        }

        Duration duration = Duration.ofMinutes(totalMinutes);
        
        // Convertion (Start Time/End Time)
        DateTimeFormatter formatter = DateTimeFormatter.ofPattern("E MMM dd HH:mm:ss O yyyy", Locale.ENGLISH);
        LocalTime startTime = LocalTime.parse(startTimeText, formatter);
        LocalTime endTime = LocalTime.parse(endTimeText, formatter);
        
        String created_by = logged_in_admin.getUser_id();

        LocalDate date = LocalDate.now(); 
        
        ClassModel cm = new ClassModel(
            class_id, 
            class_name, 
            day, 
//            duration, s
            startTime, 
            endTime, 
            created_by, 
            date,
            selected_module
        );

        String[] create_class_status = logged_in_admin.createClassGroup(cm);

        boolean status = Boolean.parseBoolean(create_class_status[0]);
        String status_message = create_class_status[1];
        
        if(status){
            
            // Clear input
            moduleIdComboBox.setSelectedIndex(0);
//            classId_field.setText(generateClassId());
            dayComboBox.setSelectedIndex(0);
            durationComboBox.setSelectedIndex(0);
            setUpStartTimeSpinner();
            setUpEndTimeSpinner();
            
            JOptionPane.showMessageDialog(this, 
                "Class created successfully!\nClass ID: " + class_id + 
                "\nModule: " + selected_module.getModuleId() + 
                "\nDate Created: " + date, 
                "Success", 
                JOptionPane.INFORMATION_MESSAGE
            );

            AdminDashboardFrame adf = new AdminDashboardFrame(logged_in_admin);
            adf.setVisible(true);
            this.dispose();
            
        }else{
            
            JOptionPane.showMessageDialog(this, 
                "Failed to create class.\nReason: " + status_message, 
                "Error", 
                JOptionPane.ERROR_MESSAGE
            );
            
        }
        
    }//GEN-LAST:event_createButtonActionPerformed

