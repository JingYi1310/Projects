    private void updateModuleName(List<Module> allModules) {
        String selectedModuleId = (String) moduleIdComboBox.getSelectedItem();

        if (selectedModuleId == null) {
            moduleNameLabel.setText("");
            return;
        }

        for (Module module : allModules) {
            if (module.getModuleId().equals(selectedModuleId)) {
                moduleNameLabel.setText(module.getModuleName());

                return;
            }
        }
    }

    
