    private void applyButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_applyButtonActionPerformed
        
        try{
            
            String grade_id = gradeIdLabel.getText().trim();
            String minMarkText = min_mark_field.getText().trim();
            String maxMarkText = max_mark_field.getText().trim();
            String description = description_field.getText().trim();
            String gpaText = gpa_field.getText().trim();

            if (minMarkText.isEmpty() || maxMarkText.isEmpty() || gpaText.isEmpty() || description.isEmpty()) {
                JOptionPane.showMessageDialog(this, "All fields must be filled out.");
                return;
            }
            
            int min_marks = Integer.parseInt(minMarkText);
            int max_marks = Integer.parseInt(maxMarkText);
            double gpa = Double.parseDouble(gpaText);
            
            // Validation
            Grade validated_grade = new Grade(grade_id, min_marks, max_marks, "", description, gpa);
            if(!validated_grade.isValidRange()){
                JOptionPane.showMessageDialog(this, "Min mark cannot be greater than Max mark.");
                return;
            }

            // Check overlaping
            for(Grade grade: grade_lines){
                if(grade.getGradeId().equals(grade_id)){
                    System.out.println("same grade id");
                    continue;
                }else{
                    if(validated_grade.overlaps(grade)){
                        System.out.println("Validated grade: " + validated_grade.getGradeId());
                        System.out.println("Grade: " + grade.getGradeId());
                        JOptionPane.showMessageDialog(this, "Mark range overlaps with grade " + grade.getGradeId());
                        return;
                    }
                }
            }
            
            // min mark and max mark range
            if (min_marks < 0 || max_marks > 100) {
                JOptionPane.showMessageDialog(this, "Marks must be between 0 and 100.");
                return;
            }

            for(Grade grade: grade_lines){
                if(grade.getGradeId().equals(grade_id)){
                    grade.setMinMark(min_marks);
                    grade.setMaxMark(max_marks);
                    grade.setDescription(description);
                    grade.setGpa(gpa);
                    break;
                }
            }

            JOptionPane.showMessageDialog(this, "Changes applied. Remember to Save All.");
            refreshTable();
            
        }catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this, "Min mark, Max mark, and GPA must be numeric.");
        }
        
    }//GEN-LAST:event_applyButtonActionPerformed

    private void saveButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveButtonActionPerformed
        
        List<Grade> gradesByMark = new ArrayList<>(grade_lines);
        gradesByMark.sort(Comparator.comparingInt(Grade::getMinMark));

        // Must start at 0
        if (gradesByMark.get(0).getMinMark() != 0) {
            JOptionPane.showMessageDialog(this,
                "Grades must start from mark 0.");
            return;
        }

        // Must end at 100
        if (gradesByMark.get(gradesByMark.size() - 1).getMaxMark() != 100) {
            JOptionPane.showMessageDialog(this,
                "Grades must end at mark 100.");
            return;
        }
        
        // GPA validation
        double previousGpa = Double.MAX_VALUE;

        List<Grade> gradesById = new ArrayList<>(grade_lines);
        gradesById.sort(
            Comparator.comparingInt(g ->
                Integer.parseInt(g.getGradeId().substring(2)))
        );

        for (Grade g : gradesById) {
            double gpa = g.getGpa();

            // GPA range check
            if (gpa < 0.0 || gpa > 4.0) {
                JOptionPane.showMessageDialog(this,
                    "GPA for " + g.getGradeId()
                    + " must be between 0.0 and 4.0");
                return;
            }

            // GPA must decrease
            if (gpa >= previousGpa) {
                JOptionPane.showMessageDialog(this,
                    "GPA for " + g.getGradeId()
                    + " must be lower than the previous grade");
                return;
            }

            previousGpa = gpa;
        }
        
        String[] updated_status = logged_in_admin.updateGrade(grade_lines);
        boolean status = Boolean.parseBoolean(updated_status[0]);
        String updated_status_message = updated_status[1];
        
        JOptionPane.showMessageDialog(this, updated_status_message);
        
        if(status){
            refreshTable();
            AdminDashboardFrame amf = new AdminDashboardFrame(logged_in_admin);
            amf.setVisible(true);
            this.dispose();
        }
        
    }//GEN-LAST:event_saveButtonActionPerformed

