    public void getRow(){
        
        int view_row = gradeTable.getSelectedRow();
        if(view_row != -1){
            int model_row = gradeTable.convertRowIndexToModel(view_row);
            String grade_id = grade_model.getValueAt(model_row, 0).toString();
            int min_mark = (int) grade_model.getValueAt(model_row, 1);
            int max_mark = (int) grade_model.getValueAt(model_row, 2);
            String grade = grade_model.getValueAt(model_row, 3).toString();
            String description = grade_model.getValueAt(model_row, 4).toString();
            String gpa = grade_model.getValueAt(model_row, 5).toString();
            
            gradeIdLabel.setText(grade_id);
            min_mark_field.setText(String.valueOf(min_mark));
            max_mark_field.setText(String.valueOf(max_mark));
            gradeLabel.setText(grade);
            description_field.setText(description);
            gpa_field.setText(gpa);
        }
    }
    
    private void refreshTable(){
        grade_model.setRowCount(0);
        for(Grade grade: grade_lines){
            Object[] row = new Object[]{
                grade.getGradeId(),
                grade.getMinMark(),
                grade.getMaxMark(),
                grade.getGrade(),
                grade.getDescription(),
                grade.getGpa()
            };
            
            grade_model.addRow(row);
        }
    }
    
