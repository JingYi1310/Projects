    private void addFieldListeners() {
        
        // For text fields - detect text changes
        id_field.getDocument().addDocumentListener((SimpleDocumentListener) () -> checkFields());
        name_field.getDocument().addDocumentListener((SimpleDocumentListener) () -> checkFields());
        email_field.getDocument().addDocumentListener((SimpleDocumentListener) () -> checkFields());
        password_field.getDocument().addDocumentListener((SimpleDocumentListener) () -> checkFields());
        contact_no_field.getDocument().addDocumentListener((SimpleDocumentListener) () -> checkFields());

        // For combo boxes - detect selection changes
        genderComboBox.addActionListener(e -> checkFields());
        roleComboBox.addActionListener(e -> checkFields());
        
        dobChooser.getDateEditor().addPropertyChangeListener(evt -> {
            if ("date".equals(evt.getPropertyName())) {
                checkFields();
            }
        });
        
    }

    private void checkFields() {

        String id = id_field.getText().trim();
        String name = name_field.getText().trim();
        String email = email_field.getText().trim();
        char[] passwordChars = password_field.getPassword();
        boolean hasPassword = passwordChars.length > 0;
        String contact = contact_no_field.getText().trim();

        // Get selected items from combo boxes
        String gender = (String) genderComboBox.getSelectedItem();
        String role = (String) roleComboBox.getSelectedItem();
        
        Date selectedDate = dobChooser.getDate();
        boolean hasDOB = selectedDate != null;

        boolean allFilled = !id.isEmpty() &&
                            !name.isEmpty() &&
                            !email.isEmpty() &&
                            hasPassword &&
                            hasDOB &&
                            !contact.isEmpty() &&
                            gender != null &&
                            !gender.isEmpty() &&
                            role != null &&
                            !role.isEmpty() &&
                            !role.equals("Select Role");

        // Enable or disable the button
        createUserButton.setEnabled(allFilled);
    }
    
