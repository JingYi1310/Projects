    public String generateNewUserId(String role){
        
        if (role == null || role.equals("Select Role")) {
            return ""; 
        }
        
        String prefix;
        int max_number = 0;
        
        switch(role){
            case "Academic Leader":
                prefix = "AL";
                break;
            case "Lecturer":
                prefix = "L";
                break;
            case "Student":
                prefix = "TP";
                break;
            default: 
                throw new IllegalArgumentException("Unknown role: " + role);
        }
        
        List<User> allUsers = logged_in_admin.readUser();
        for(User u: allUsers){
            
            String id = u.getUser_id();
            
            if(id.startsWith(prefix)){
                // cut prefix part, get id number
                String numeric_part = id.substring(prefix.length());
                
                try{
                    int num = Integer.parseInt(numeric_part);
                    if(num > max_number){
                        max_number = num;
                    }
                }catch(NumberFormatException e){
                    System.out.println("Skipping invalid ID: " + id);
                }
            }
        }
        
        int new_number = max_number + 1;
        return prefix + String.format("%03d", new_number);
        
    }
    
    
